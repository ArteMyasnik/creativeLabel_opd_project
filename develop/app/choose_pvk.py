# Для обратной совместимости можно создать и плоский список всех ПВК
PVK_LIST = [pvk for category in PVK_CATEGORIES.values() for pvk in category]

def process_content(content):
    return content.replace('<think>', '').replace('</think>', '')

def generate_prompt(user_word):
    # Ограничиваем количество PVK в промпте, чтобы не превысить лимиты API
    sample_pvks = PVK_LIST[:20]  # Берем первые 20 для примера
    return f"""Привет! Вот список ПВК: {sample_pvks}. 
Найди 3-5 слов из списка, которые наиболее тесно связаны по смыслу со словом "{user_word}". 
Ответ дай в виде списка, без пояснений."""

def chat_stream(prompt):
    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json"
    }
    
    data = {
        "model": MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "stream": True,
        "temperature": 0.3,
        "max_tokens": 200  # Ограничиваем длину ответа
    }

    try:
        with requests.post(
            "https://openrouter.ai/api/v1/chat/completions",
            headers=headers,
            json=data,
            stream=True,
            timeout=30  # Таймаут 30 секунд
        ) as response:
            if response.status_code != 200:
                print(f"Ошибка API: {response.status_code}, {response.text}")
                return ""

            full_response = []
            
            for chunk in response.iter_lines():
                if chunk:
                    chunk_str = chunk.decode('utf-8').replace('data: ', '')
                    try:
                        chunk_json = json.loads(chunk_str)
                        if "choices" in chunk_json:
                            content = chunk_json["choices"][0]["delta"].get("content", "")
                            if content:
                                cleaned = process_content(content)
                                print(cleaned, end='', flush=True)
                                full_response.append(cleaned)
                    except json.JSONDecodeError:
                        continue
                    except Exception as e:
                        print(f"Ошибка обработки chunk: {e}")
                        continue

            print()
            return ''.join(full_response)
            
    except requests.exceptions.RequestException as e:
        print(f"Ошибка соединения: {e}")
        return ""

def main():
    print("Система подбора ПВК по запросу \nДля выхода введите 'exit'\n")
    print("Доступные ПВК:", ", ".join(PVK_LIST[:10]), "...")  # Показываем первые 10 для примера

    while True:
        user_input = input("\nВведите ключевое слово из списка ПВК: ").strip()
        
        if user_input.lower() == 'exit':
            print("Завершение работы...")
            break
            
        if user_input not in PVK_LIST:
            print("Ошибка: выберите существующее слово из списка ПВК.")
            print("Примеры ПВК:", ", ".join(PVK_LIST[:5]), "...")
            continue
            
        print("\nПодбираем связанные ПВК...")
        prompt = generate_prompt(user_input)
        chat_stream(prompt)

if __name__ == "__main__":
    main()
